from google.colab import userdata
from langchain_groq import ChatGroq

api_key = userdata.get("GROQ_API_KEY")

llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0,
    api_key=api_key
)

print("Groq connection successful!")

SYSTEM = """
You are the assistant for Sweet Crumbs Home Bakery.

FACTS:
- We bake to order.
- Orders need 24 hours' notice.
- All cakes have eggless versions.

RULES:
- Never promise delivery times.
- If you do not know something, say so.
- Reply politely in under 60 words.
"""

def ask(question):
    messages = [
        ("system", SYSTEM),
        ("human", question)
    ]

    response = llm.invoke(messages)
    return response.content

print(ask("Can I order a chocolate cake for tomorrow?"))
print(ask("Do you have eggless cakes?"))
print(ask("Can you guarantee delivery at 5 PM?"))
print(ask("What is your bakery address?"))

