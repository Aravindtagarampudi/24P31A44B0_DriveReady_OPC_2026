from typing import Literal
from pydantic import BaseModel, Field

# Bakery menu
MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}

# Bakery opening hours
HOURS = {
    "monday": "9 am to 8 pm",
    "tuesday": "9 am to 8 pm",
    "wednesday": "9 am to 8 pm",
    "thursday": "9 am to 8 pm",
    "friday": "9 am to 8 pm",
    "saturday": "9 am to 8 pm",
    "sunday": "10 am to 6 pm"
}

# Pydantic Order model
class Order(BaseModel):
    """A cake order taken from a customer's chat message."""

    name: str = Field(
        description="Customer's first name"
    )

    item: Literal[
        "plum cake",
        "chocolate cake",
        "cupcake"
    ] = Field(description="Menu item")

    qty: int = Field(
        description="How many cakes the customer wants",
        ge=1
    )

    date: str = Field(
        description="Pickup date as the customer said it"
    )

    eggless: bool = Field(
        description="True if the customer asked for eggless"
    )

print("Bakery data and Order model created successfully!")

# CELL 3: CREATE LANGCHAIN TOOLS

from langchain.tools import tool

# TOOL 1: Get cake price
@tool
def get_price(item: str, qty: int = 1) -> str:
    """Get the total price in rupees for a quantity of one menu item.

    Args:
        item: Menu item such as plum cake, chocolate cake or cupcake.
        qty: Number of items required.
    """

    price = MENU.get(item.lower().strip())

    if price is None:
        return f"'{item}' is not on the menu. We have: {', '.join(MENU)}."

    return f"{qty} x {item} = Rs {price * qty}"


# TOOL 2: Check bakery opening hours
@tool
def is_open(day: str) -> str:
    """Check the bakery's opening hours for a day of the week."""

    hours = HOURS.get(day.lower().strip())

    if hours:
        return f"Open {hours} on {day}."

    return f"'{day}' is not a day of the week."


# TOOL 3: Save customer order
@tool
def log_order(
    name: str,
    item: str,
    qty: int,
    date: str,
    eggless: bool
) -> str:
    """Save a confirmed and validated cake order to Google Sheets.

    Use only after the customer confirms the order details.
    """

    try:
        order = Order(
            name=name,
            item=item.lower().strip(),
            qty=qty,
            date=date,
            eggless=eggless
        )

    except Exception as e:
        return f"Could not save the order: {e}. Ask the customer to correct it."

    total = MENU[order.item] * order.qty

    ws.append_row([
        order.name,
        order.item,
        order.qty,
        order.date,
        "yes" if order.eggless else "no",
        total
    ])

    return (
        f"Saved: {order.qty} x {order.item} "
        f"for {order.name} on {order.date}, Rs {total}."
    )


print("All three bakery tools created successfully!")

