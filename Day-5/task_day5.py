import os
from google.colab import userdata
from langchain_groq import ChatGroq

os.environ["GROQ_API_KEY"] = userdata.get("GROQ_API_KEY")

llm = ChatGroq(
    model="openai/gpt-oss-20b",
    temperature=0.2,
    max_retries=3
)

print("Groq LLM connected successfully!")

from google.colab import files

uploaded = files.upload()

pdf_path = next(
    (name for name in uploaded if name.lower().endswith(".pdf")),
    None
)

print("Uploaded PDF:", pdf_path)

from langchain_community.document_loaders import PyPDFLoader

loader = PyPDFLoader(pdf_path)

rag_docs = loader.load()

print("PDF loaded successfully!")
print("Total pages:", len(rag_docs))

print("\nExtracted text:")
print(rag_docs[0].page_content)

from langchain_text_splitters import RecursiveCharacterTextSplitter

text_splitter = RecursiveCharacterTextSplitter(
    chunk_size=400,
    chunk_overlap=80
)

rag_chunks = text_splitter.split_documents(rag_docs)

print("Total chunks:", len(rag_chunks))

for i, chunk in enumerate(rag_chunks):
    print(f"\n--- Chunk {i+1} ---")
    print(chunk.page_content)

from langchain_huggingface import HuggingFaceEmbeddings

embeddings = HuggingFaceEmbeddings(
    model_name="sentence-transformers/all-MiniLM-L6-v2"
)

print("Embedding model loaded successfully!")

from langchain_community.vectorstores import FAISS

vector_store = FAISS.from_documents(
    rag_chunks,
    embeddings
)

print("Vectors stored successfully in FAISS!")

question = "Why did Arjun's grandmother light a lantern outside their house?"

retrieved_docs = vector_store.similarity_search(
    question,
    k=3
)

print("Retrieved relevant chunks:\n")

for i, doc in enumerate(retrieved_docs):
    print(f"--- Retrieved Chunk {i+1} ---")
    print(doc.page_content)

context = "\n\n".join(
    doc.page_content for doc in retrieved_docs
)

prompt = f"""
You are a helpful question-answering assistant.

Answer the question using only the provided context.
If the answer is not available in the context, say:
"I don't have enough information in the document."

Context:
{context}

Question:
{question}

Answer:
"""

response = llm.invoke(prompt)

print("Question:", question)
print("\nAI Answer:")
print(response.content)

def ask_rag(question):

    retrieved_docs = vector_store.similarity_search(
        question,
        k=3
    )

    context = "\n\n".join(
        doc.page_content for doc in retrieved_docs
    )

    prompt = f"""
    Answer the question using only the given context.

    If the answer is not available, say:
    "I don't have enough information in the document."

    Context:
    {context}

    Question:
    {question}

    Answer:
    """

    response = llm.invoke(prompt)

    print("Question:", question)
    print("\nAnswer:", response.content)

    print("\nSources:")
    for doc in retrieved_docs:
        print("Page:", doc.metadata.get("page", 0) + 1)

    return response.content

ask_rag("Who is Arjun?")

ask_rag("What happened during the stormy night?")

ask_rag("How did Arjun help the traveler?")

ask_rag("What lesson did Arjun learn from his grandmother?")

ask_rag("What was the traveler's name?")