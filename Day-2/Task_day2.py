MAX_TURNS = 2
history = [
    {"role": "system", "content": SYSTEM}
]

def memory_chat(message):
    history.append({
        "role": "user",
        "content": message
    })

    response = client.chat.completions.create(
        model="openai/gpt-oss-120b",
        messages=history[-(MAX_TURNS * 2 + 1):]
    )

    answer = response.choices[0].message.content

    history.append({
        "role": "assistant",
        "content": answer
    })

    print("Bot:", answer)

