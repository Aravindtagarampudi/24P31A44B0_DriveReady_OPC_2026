SYSTEM_CUSTOM = """
You are the customer assistant for Sweet Crumbs Home Bakery.

FACTS:
1. We prepare cakes after receiving an order.
2. We offer chocolate, vanilla and butterscotch cakes.
3. Eggless cakes are available.
4. Orders require at least 24 hours' notice.
5. Customers can request custom cake designs.

RULES:
1. Never invent cake prices.
2. Never promise a delivery time.
3. If information is missing, ask the customer to contact the bakery owner.

Reply politely and clearly.
"""

def bakery_assistant(question):
    messages = [
        ("system", SYSTEM_CUSTOM),
        ("human", question)
    ]

    response = llm.invoke(messages)
    return response.content

print("QUESTION 1:")
print(bakery_assistant("Do you have eggless birthday cakes?"))

print("\nQUESTION 2:")
print(bakery_assistant("Can I order a custom cake for tomorrow?"))

print("\nQUESTION 3:")
print(bakery_assistant("What is the price of a 2 kg chocolate cake?"))