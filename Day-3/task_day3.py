MENU = {
    "plum cake": 500,
    "chocolate cake": 650,
    "cupcake": 80
}

def get_price(item: str, quantity: int = 1) -> int:
    """Calculate the total price of a menu item."""

    item = item.lower().strip()

    if item not in MENU:
        raise ValueError("Item not found in menu.")

    if quantity <= 0:
        raise ValueError("Quantity must be greater than zero.")

    return MENU[item] * quantity


def check_order_notice(hours_notice: int) -> bool:
    """Check whether an order meets the 24-hour notice requirement."""

    return hours_notice >= 24


